async function start() {
  try {
    await initDb();

    app.listen(PORT, () => {
      console.log(`7Perfection Debt Tool running on port ${PORT}`);
    });
  } catch (e) {
    console.error("Database startup error:", e);
    process.exit(1);
  }
}

start();