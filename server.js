app.post("/api/change-pin", auth, async (req, res) => {
  try {
    const old = String(req.body.oldPin || "");
    const next = String(req.body.newPin || "");

    const { rows } = await pool.query(
      "SELECT * FROM users WHERE id=1"
    );

    const u = rows[0];

    if (!u || !bcrypt.compareSync(old, u.pin_hash)) {
      return res.status(401).json({ error: "PIN aktyèl la pa bon." });
    }

    if (!/^\d{4,6}$/.test(next)) {
      return res.status(400).json({
        error: "Nouvo PIN lan dwe gen 4–6 chif."
      });
    }

    await pool.query(
      "UPDATE users SET pin_hash=$1 WHERE id=1",
      [bcrypt.hashSync(next, 12)]
    );

    res.clearCookie("session");
    res.json({ ok: true });
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: "Erè nan chanje PIN lan." });
  }
});

